"""Regenerate the side-11 integer certificate (LP solver is not used by Lean)."""
from collections import defaultdict
from fractions import Fraction
from pathlib import Path
import inspect
import subprocess

from . import patch_square as patch
from .residue_zero_lean_stencil import encode


def physical_rows():
    # Expose the physical endpoints of unpooled marginal rows. This changes
    # only their labels; assert that the actual LP is identical.
    src = inspect.getsource(patch.relaxation)
    src = src.replace("None if pooled is None else", "")
    src = src.replace("if pooled is None:add(diff(a,b));return",
                      "if pooled is None:add(diff(a,b),tag=tag);return")
    src = src.replace("def coarse(i,j,S):", "def coarse(i,j,S):\n        if pooled is None:return i,j")
    ns = vars(patch).copy()
    exec(src, ns)
    tags = []
    model = ns["relaxation"](11, tags=tags)
    assert model == patch.relaxation(11)
    return model, tags


def main():
    (_, rows, obj), tags = physical_rows()
    lp = "max: " + patch.lpterms(obj) + ";\n" + "".join(
        f"r{i}: {patch.lpterms(dict(c))} {op} {rhs};\n"
        for i, (c, op, rhs) in enumerate(rows))
    out = subprocess.run(["lp_solve", "-presolve", "-S4"], input=lp, text=True,
                         capture_output=True, check=True)
    tables = defaultdict(dict)
    for line in out.stdout.split("Dual values with from - till limits:")[-1].splitlines():
        words = line.split()
        if len(words) != 4 or not words[0].startswith("r") or not words[0][1:].isdigit():
            continue
        price = Fraction(words[1])
        if not price:
            continue
        sign, row = tags[int(words[0][1:])]
        tag = row[0]
        if tag == "star norm":
            row = tag, tuple(i if i < 6 else i + 4 for i in row[1])
        key = encode(row)
        assert key not in tables[tag]
        tables[tag][key] = round(100000 * price * sign)
    for tag, n, d in [("star norm", 11, 6), ("patch norm", 9, 5)]:
        for i in range(n):
            for j in range(n):
                def axis(x):
                    return x if x < d else 2*d + 3 + x - n
                k = axis(i)*16 + axis(j)
                tables[tag][k] = tables[tag].get(k, 0) + 10
    dest = Path(__file__).resolve().parents[2] / "lean/GridGraphs/Results/SmallDiagonalExact/Eleven/Prices.lean"
    dest.parent.mkdir(exist_ok=True)
    with dest.open("w") as out:
        print("import Std\n\n/-! Integer prices generated by `eleven_prices.py`. "
              "Lean checks every local bill. -/\nnamespace GridGraphs.Eleven\n"
              "\ndef scale : Int := 100000", file=out)
        for tag, name in [("corner","corner"), ("star norm","starNorm"), ("patch norm","patchNorm"),
                          ("s","edge"), ("sp","incidence"), ("pp","overlap")]:
            vals = [f"({k},{v})" for k,v in sorted(tables[tag].items())]
            body = ",\n  ".join(", ".join(vals[i:i+4]) for i in range(0,len(vals),4))
            print(f"\ndef {name}Prices : Std.HashMap Nat Int := .ofList [\n  {body}]", file=out)
        print("\nend GridGraphs.Eleven", file=out)
    print("Corner price", tables["corner"], "budget",
          sum(sum(tables[t].values()) for t in ("star norm","patch norm","corner")))


if __name__ == "__main__":
    main()
