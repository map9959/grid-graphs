"""Export the unrestricted period-three physical price tables for Lean.

This is the unpooled stencil, including the single negative corner price.
No LP construction or solver is used.
"""
import json
import math
from fractions import Fraction
from pathlib import Path

from .residue_zero_lean_stencil import encode


def main():
    here = Path(__file__).resolve().parent
    entries = json.loads((here/'square_dual_stencil.json').read_text())
    scale = math.lcm(*(Fraction(v).denominator for _, v in entries))
    dest = here.parents[1]/'lean/GridGraphs/ResidueTwoUpper/StencilPrices.lean'
    with dest.open('w') as out:
        print('import Std\n\n/-! Generated by `residue_two_upper_stencil.py` from '
              '`square_dual_stencil.json`. -/\nnamespace GridGraphs.ResidueTwoUpper.Stencil', file=out)
        print(f'\ndef scale : Int := {scale}', file=out)
        for tag, name in [('corner', 'corner'), ('star norm', 'starNorm'),
                          ('patch norm', 'patchNorm'), ('s', 'edge'), ('sp', 'incidence'),
                          ('pp', 'overlap')]:
            table = {}
            for k, v in entries:
                if k[0] == tag:
                    price = Fraction(v)*scale
                    assert price.denominator == 1 and encode(k) not in table
                    table[encode(k)] = int(price)
            pairs = ',\n  '.join(f'({k}, {v})' for k, v in table.items())
            print(f'\ndef {name}Prices : Std.HashMap Nat Int := .ofList [\n  {pairs}]', file=out)
        print('\nend GridGraphs.ResidueTwoUpper.Stencil', file=out)


if __name__ == '__main__':
    main()
