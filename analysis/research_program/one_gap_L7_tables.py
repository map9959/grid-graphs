"""Export the 5 transverse by 33 longitudinal domain bitmaps at the base 35.
Every word is checked against the physical dual in L7Catalogue.lean. The
generator and its Python dependencies are unnecessary for Lean replay.
"""
from pathlib import Path
from .one_gap_L7_probe import templates

def main():
    dom=templates(35); words=[]; ids=[]
    for r in range(5):
        for j in range(33):
            w=sum(1<<m for m in dom(r,j))
            if w not in words:words.append(w)
            ids.append(words.index(w))
    file=Path(__file__).resolve().parents[2]/'lean/GridGraphs/ResidueTwoUpper/OneGap/L7Data.lean'
    file.write_text('''import Std

/-! Seven-layer L strip: distinct necessary mask domains at side 35.
Generated by `one_gap_L7_tables.py`; checked independently in Lean. -/
namespace GridGraphs.ResidueTwoUpper.Exceptional.OneGap.L7

def words : Array Nat := #[\n  '''+',\n  '.join(hex(w) for w in words)+']\n\ndef indices : Array Nat := #[\n  '+',\n  '.join(','.join(map(str,ids[i:i+33])) for i in range(0,165,33))+']\n\ndef allowed (r j m : Nat) := words[indices[33*r+j]!]!.testBit m\n\nend GridGraphs.ResidueTwoUpper.Exceptional.OneGap.L7\n');print(len(words),file.stat().st_size)
if __name__=='__main__':main()
